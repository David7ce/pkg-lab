/** Strings for an ISO 639 language code ("pt-BR" and "ES" work); English for anything not translated. */
fun stringsFor(languageCode: String): Strings = when (languageCode.lowercase().take(2)) {
    "es" -> EsStrings
    "fr" -> FrStrings
    "de" -> DeStrings
    "pt" -> PtStrings
    "it" -> ItStrings
    else -> EnStrings
}

