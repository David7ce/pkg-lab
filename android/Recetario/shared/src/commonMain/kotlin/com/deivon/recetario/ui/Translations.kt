/** Languages the app offers. [code] is the ISO 639 code; System follows the device. Names are shown in their own language. */
enum class AppLanguage(val code: String?, val nativeName: String) {
    System(null, ""),
    Es("es", "Español"),
    En("en", "English"),
    Fr("fr", "Français"),
    De("de", "Deutsch"),
    Pt("pt", "Português"),
    It("it", "Italiano"),
}

/** Strings for an ISO 639 language code; English for anything not translated. */
fun stringsFor(languageCode: String): Strings = when (languageCode.lowercase().take(2)) {
    "es" -> EsStrings
    "fr" -> FrStrings
    "de" -> DeStrings
    "pt" -> PtStrings
    "it" -> ItStrings
    else -> EnStrings
}

